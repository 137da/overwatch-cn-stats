async (page, { baseUrl = 'http://127.0.0.1:18765' } = {}) => {
  const passed = [];
  const check = (value, message) => { if (!value) throw Error(message); passed.push(message); };
  const query = async (tag = '晚风#1024') => { await page.locator('#tag').fill(tag); await page.locator('#search-form').evaluate(f => f.requestSubmit()); await page.waitForFunction(() => !document.querySelector('#btn-search').disabled); };
  await page.goto(`${baseUrl}/index.html`);
  await page.locator('#account-summary').filter({ hasText: '已就绪' }).waitFor();
  await query();
  await page.evaluate(async () => {
    const base = await window.pywebview.api.get_match_detail('0', 'mock');
    window.pywebview.api.get_match_detail = async id => { await new Promise(r => setTimeout(r, id === '0' ? 350 : 10)); const result = structuredClone(base); result.data.mapName = id === '0' ? '旧对局' : '新对局'; return result; };
  });
  await page.locator('#matches .match').first().click();
  await page.keyboard.press('Escape');
  await page.locator('#matches .match').nth(1).click();
  await page.waitForFunction(() => document.querySelector('#detail').textContent.includes('新对局'));
  await page.waitForTimeout(400);
  check(await page.locator('#detail').innerText().then(t => t.includes('新对局') && !t.includes('旧对局')), '关闭旧详情后，迟到响应不会覆盖新对局');
  await page.keyboard.press('Escape');
  await page.evaluate(() => {
    window.pywebview.api.get_player = async params => { if (params.page > 1) await new Promise(r => setTimeout(r, 350)); const data = structuredClone(window.__fixture.playerData); data.profile.name = params.battleTag.split('#')[0]; return { ok: true, data }; };
  });
  await page.locator('#btn-more').click();
  await query('新玩家#7788');
  await page.waitForTimeout(400);
  check(await page.locator('#matches .match').count() === 6, '旧玩家迟到的分页不会接到新玩家后面');
  check(await page.locator('#profile .name').innerText() === '新玩家', '新玩家资料保持正确');
  await page.reload();
  await page.locator('#account-summary').filter({ hasText: '已就绪' }).waitFor();
  await page.evaluate(() => { const d = window.__fixture.playerData; d.ranks.forEach(r => { r.rankName = ''; r.matchSum = 0; }); d.overview.sport = {}; d.profile.title = '<img src=x onerror=alert(1)>'; });
  await query('名字<测试>#1024');
  const colors = await page.locator('#ranks .rank').evaluateAll(cards => cards.map(c => getComputedStyle(c).backgroundColor));
  check(colors.every(c => c === colors[0]), '全部未定级时所有职责卡同灰色');
  check(await page.locator('#avg').innerText().then(t => t.includes('没有竞技记录')), '没有统计数据时展示空状态');
  check(await page.locator('#profile img').count() === 0 && await page.locator('#profile .name').innerText() === '名字<测试>', '玩家名字与头衔中的 HTML 被安全转义');
  await page.evaluate(() => { window.__fixture.playerData.ranks[0].rankName = '未知段位'; window.__fixture.playerData.ranks[0].matchSum = 1; });
  await query();
  const unknown = await page.locator('#ranks .rank').evaluateAll(cards => cards.map(c => getComputedStyle(c).backgroundColor));
  check(unknown[0] === unknown[1], '未知段位回退到统一灰色');
  await page.evaluate(() => { window.__fixture.error = 'reject'; });
  await page.locator('#btn-more').click();
  await page.waitForFunction(() => !document.querySelector('#btn-more').disabled);
  check(await page.locator('#notice').isVisible(), '分页桥接异常后显示错误且可重试');
  await page.evaluate(() => { window.__fixture.error = null; });
  await page.locator('#btn-accounts').click();
  await page.locator('#accounts .account').first().locator('summary.head').click();
  await page.evaluate(() => { window.pywebview.api.start_login = async () => { await new Promise(r => setTimeout(r, 350)); return { ok: true, data: 'data:image/svg+xml,<svg xmlns="http://www.w3.org/2000/svg"/>' }; }; });
  await page.locator('[data-login="query"]').click();
  await page.locator('#btn-login-back').click();
  await page.waitForTimeout(400);
  check(await page.locator('#view-main').isVisible(), '取消扫码后，迟到响应不会重新切回登录页');
  check(await page.locator('#qr').getAttribute('src') === null, '取消扫码后，不显示迟到的二维码');
  await page.reload();
  await page.locator('#account-summary').filter({ hasText: '已就绪' }).waitFor();
  await page.evaluate(() => {
    window.__fixture.delay = 300;
    window.pywebview.api.report_check = async () => ({ ok: true, data: { checkedAt: '刚刚', windowMin: 30, alert: { battleTag: '举报目标#1001', batchSize: 1 }, players: [] } });
  });
  await page.locator('#tag').fill('当前玩家#1024');
  await page.locator('#search-form').evaluate(form => form.requestSubmit());
  await page.locator('#btn-reports').click();
  await page.locator('#report-toggle').check();
  await page.waitForFunction(() => !document.querySelector('#btn-search').disabled && document.querySelector('#profile .name')?.textContent === '举报目标');
  let requests = await page.evaluate(() => window.__fixture.calls.filter(c => c.name === 'get_player').map(c => c.args[0].battleTag));
  check(requests.join(',') === '当前玩家#1024,举报目标#1001', '查询中收到举报时顺序查询目标，不丢失自动查询');
  await page.locator('#btn-reports').click();
  await page.locator('#report-toggle').uncheck();
  await page.keyboard.press('Escape');
  await page.evaluate(() => { window.__fixture.error = 'rate_limited'; });
  await page.locator('#search-form').evaluate(form => form.requestSubmit());
  await page.locator('#btn-reports').click();
  await page.locator('#report-toggle').check();
  await page.waitForFunction(() => !document.querySelector('#btn-search').disabled);
  requests = await page.evaluate(() => window.__fixture.calls.filter(c => c.name === 'get_player'));
  check(requests.length === 3, '当前查询限流后不继续排队的自动举报查询');
  await page.locator('#btn-reports').click();
  await page.locator('#report-toggle').uncheck();
  await page.keyboard.press('Escape');
  return { checks: passed.length, passed };
}
